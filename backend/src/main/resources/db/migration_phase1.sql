CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    district VARCHAR(255),
    organization_name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS societal_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    domain VARCHAR(255) NOT NULL,
    domain_name VARCHAR(255) NOT NULL,
    urgency VARCHAR(255) NOT NULL,
    priority VARCHAR(50) DEFAULT 'MODERATE',
    estimated_severity VARCHAR(255),
    model_confidence DOUBLE PRECISION,
    priority_explanation TEXT,
    ai_suggested_description TEXT,
    needs_human_review BOOLEAN DEFAULT FALSE,
    safety_flags VARCHAR(255),
    priority_override_reason TEXT,
    priority_overridden_by VARCHAR(255),
    cluster_id BIGINT,
    is_cluster_master BOOLEAN DEFAULT TRUE,
    duplicate_count INTEGER DEFAULT 1,
    submitter_type VARCHAR(255) NOT NULL,
    submitter_name VARCHAR(255) NOT NULL,
    citizen_email VARCHAR(255) NOT NULL,
    district VARCHAR(255) NOT NULL,
    block VARCHAR(255) NOT NULL,
    panchayat VARCHAR(255) NOT NULL,
    location_text VARCHAR(255),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    affected_population INTEGER,
    evidence_image_url TEXT,
    status VARCHAR(255) NOT NULL,
    assigned_hei VARCHAR(255),
    assigned_hei_department VARCHAR(255),
    faculty_mentor VARCHAR(255),
    student_team VARCHAR(255),
    industry_partner VARCHAR(255),
    prototype_details TEXT,
    pilot_results TEXT,
    citizen_verification_requested BOOLEAN DEFAULT FALSE,
    citizen_feedback_notes TEXT,
    upvotes INTEGER DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

