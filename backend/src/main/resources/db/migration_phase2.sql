-- 2. Maintenance Staff per Society
CREATE TABLE IF NOT EXISTS maintenance_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    role VARCHAR(100) NOT NULL, -- Electrician, Plumber, Lift Technician, Housekeeping, Security
    phone VARCHAR(50) NOT NULL,
    is_available BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

-- 3. Society Maintenance Issues (Independent from civic challenges)
CREATE TABLE IF NOT EXISTS society_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(100) NOT NULL,
    priority VARCHAR(50) NOT NULL DEFAULT 'MODERATE',
    status VARCHAR(50) NOT NULL DEFAULT 'REPORTED', -- REPORTED, ACKNOWLEDGED, IN_PROGRESS, RESOLVED, CLOSED
    building_tower VARCHAR(100) NOT NULL,
    unit_floor VARCHAR(100) NOT NULL,
    resident_name VARCHAR(255) NOT NULL,
    resident_email VARCHAR(255) NOT NULL,
    resident_phone VARCHAR(50),
    assigned_staff_name VARCHAR(255),
    assigned_staff_role VARCHAR(100),
    assigned_staff_phone VARCHAR(50),
    evidence_image_url TEXT,
    ai_suggested_description TEXT,
    cluster_id BIGINT,
    is_cluster_master BOOLEAN DEFAULT TRUE,
    duplicate_count INTEGER DEFAULT 1,
    safety_flags VARCHAR(255),
    emergency_guidance TEXT,
    needs_human_review BOOLEAN DEFAULT FALSE,
    resolution_notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    resolved_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_society_issues_org ON society_issues(organization_id);
CREATE INDEX IF NOT EXISTS idx_society_issues_status ON society_issues(status);
CREATE INDEX IF NOT EXISTS idx_society_issues_cluster ON society_issues(cluster_id);

-- 4. Society Issue Audit Logs (Immutable status and assignment tracking)
CREATE TABLE IF NOT EXISTS society_issue_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES society_issues(id) ON DELETE CASCADE,
    organization_id BIGINT NOT NULL,
    actor_email VARCHAR(255) NOT NULL,
    actor_role VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL, -- STATUS_CHANGE, STAFF_ASSIGNMENT, PRIORITY_OVERRIDE, RESOLUTION
    previous_status VARCHAR(50),
    new_status VARCHAR(50),
    notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_society_audits_issue ON society_issue_audits(issue_id);

